    vendeur_raison_sociale = (select e.raison_sociale from entreprise e where e.id = facture.entreprise_id),
    vendeur_siren = (select e.siren from entreprise e where e.id = facture.entreprise_id),
    vendeur_tva_intra = (select e.tva_intra from entreprise e where e.id = facture.entreprise_id),
    vendeur_adresse = (select e.adresse from entreprise e where e.id = facture.entreprise_id),
    vendeur_code_postal = (select e.code_postal from entreprise e where e.id = facture.entreprise_id),
    vendeur_ville = (select e.ville from entreprise e where e.id = facture.entreprise_id),
    vendeur_iban = (select e.iban from entreprise e where e.id = facture.entreprise_id),
    vendeur_bic = (select e.bic from entreprise e where e.id = facture.entreprise_id),
    vendeur_option_tva_debits = (select e.option_tva_debits from entreprise e where e.id = facture.entreprise_id),
    acheteur_raison_sociale = (select c.raison_sociale from client c where c.id = facture.client_id),
    acheteur_siren = (select c.siren from client c where c.id = facture.client_id),
    acheteur_tva_intra = (select c.tva_intra from client c where c.id = facture.client_id),
    acheteur_adresse = (select c.adresse from client c where c.id = facture.client_id),
    acheteur_code_postal = (select c.code_postal from client c where c.id = facture.client_id),
    acheteur_ville = (select c.ville from client c where c.id = facture.client_id)
where numero is not null;

-- Le fichier Factur-X émis, conservé tel quel : c'est lui qui fait foi.
create table facture_document (
    id bigint generated by default as identity primary key,
    entreprise_id bigint not null references entreprise,
    facture_id bigint not null unique references facture,
    contenu bytea not null,
    sha256 varchar(64) not null,
    cree_le timestamp with time zone not null
);
