create table entreprise (
    id bigint generated by default as identity primary key,
    raison_sociale varchar(200) not null,
    siren varchar(9) not null unique,
    siret varchar(14),
    tva_intra varchar(20),
    adresse varchar(200) not null,
    code_postal varchar(10) not null,
    ville varchar(100) not null,
    iban varchar(34),
    bic varchar(11),
    option_tva_debits boolean not null default false
);

create table utilisateur (
    id bigint generated by default as identity primary key,
    email varchar(200) not null unique,
    mot_de_passe_hash varchar(100) not null,
    entreprise_id bigint not null references entreprise
);

create table client (
    id bigint generated by default as identity primary key,
    entreprise_id bigint not null references entreprise,
    raison_sociale varchar(200) not null,
    siren varchar(9) not null,
    tva_intra varchar(20),
    adresse varchar(200) not null,
    code_postal varchar(10) not null,
    ville varchar(100) not null,
    email varchar(200)
);
create index client_entreprise on client (entreprise_id);

create table site (
    id bigint generated by default as identity primary key,
    entreprise_id bigint not null references entreprise,
    client_id bigint not null references client,
    nom varchar(200) not null,
    adresse varchar(200) not null,
    code_postal varchar(10) not null,
    ville varchar(100) not null
);
create index site_client on site (client_id);

create table contrat (
    id bigint generated by default as identity primary key,
    entreprise_id bigint not null references entreprise,
    site_id bigint not null references site,
    libelle varchar(300) not null,
    montant_mensuel_ht numeric(12, 2) not null,
    taux_tva numeric(5, 2) not null,
    date_debut date not null,
    date_fin date
);
create index contrat_entreprise on contrat (entreprise_id);

create table facture (
    id bigint generated by default as identity primary key,
    entreprise_id bigint not null references entreprise,
    client_id bigint not null references client,
    numero varchar(30),
    statut varchar(20) not null,
    date_emission date,
    date_echeance date,
    periode varchar(7),
    total_ht numeric(12, 2) not null,
    total_tva numeric(12, 2) not null,
    total_ttc numeric(12, 2) not null,
    id_depot varchar(100),
    constraint facture_numero_unique unique (entreprise_id, numero)
);

create table ligne_facture (
    id bigint generated by default as identity primary key,
    entreprise_id bigint not null references entreprise,
    facture_id bigint not null references facture,
    contrat_id bigint references contrat,
    periode varchar(7),
    designation varchar(500) not null,
    quantite numeric(12, 3) not null,
    prix_unitaire_ht numeric(12, 2) not null,
    taux_tva numeric(5, 2) not null,
    -- un contrat ne peut être facturé qu'une fois par mois
    constraint ligne_contrat_periode_unique unique (contrat_id, periode)
);
create index ligne_facture_facture on ligne_facture (facture_id);

create table compteur_facture (
    id bigint generated by default as identity primary key,
    entreprise_id bigint not null references entreprise,
    annee int not null,
    dernier_numero int not null,
    constraint compteur_unique unique (entreprise_id, annee)
);
